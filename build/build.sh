#!/usr/bin/env bash
# In-container Buildroot builder. Invoked by build/Dockerfile.
#
# Same Buildroot version, same "concatenate defconfigs, last assignment wins"
# trick as openHC (see openHC/build/build.sh) — this just adds a third layer.
# The effective defconfig is:
#
#   openHC/board/ea-common/ea-common_defconfig   (shared EA family base)
#   + openHC/board/ea1/ea1_defconfig              (EA1-only deltas)
#   + board/ea1-ha/ea1-ha_defconfig                (Home Assistant deltas, this repo)
#
# BR2_EXTERNAL points at BOTH external trees (Buildroot supports a
# space-separated list), so ea1-ha_defconfig can reference
# $(BR2_EXTERNAL_OPENHC_PATH) the same way openHC's own board files do.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
OPENHC_DIR="${OPENHC_DIR:-$REPO/openHC}"
BOARD="ea1-ha"
BUILDROOT_DIR="${BUILDROOT_DIR:-/opt/buildroot}"
OUT="${BR2_OUTPUT_DIR:-$REPO/output/build/$BOARD}"
DL="${BR2_DL_DIR:-$REPO/dl}"

[ -f "$OPENHC_DIR/board/ea-common/ea-common_defconfig" ] || {
    echo "no openHC checkout at $OPENHC_DIR (submodule not initialized?)" >&2
    echo "  git submodule update --init openHC" >&2
    exit 1
}

EFFECTIVE="$OUT/openhc-ha-${BOARD}.defconfig"
mkdir -p "$OUT" "$DL"
{
    echo "# GENERATED by build/build.sh — do not edit."
    echo "# openHC/ea-common + openHC/ea1 + ea1-ha (this repo)"
    echo
    cat "$OPENHC_DIR/board/ea-common/ea-common_defconfig"
    echo
    cat "$OPENHC_DIR/board/ea1/ea1_defconfig"
    echo
    cat "$REPO/board/ea1-ha/ea1-ha_defconfig"
} > "$EFFECTIVE"
echo ">> defconfig: $EFFECTIVE"

cpu=$(nproc)
memkb=$(awk '/^MemTotal:/{print $2}' /proc/meminfo)
memjobs=$(( memkb / 2500000 )); [ "$memjobs" -lt 1 ] && memjobs=1
JOBS="${BR2_JLEVEL:-$cpu}"
[ "$memjobs" -lt "$JOBS" ] && JOBS="$memjobs"
echo ">> BR2_JLEVEL=$JOBS (cpu=$cpu, mem-safe=$memjobs, MemTotal=$((memkb/1024))MB)"

[ -f "$BUILDROOT_DIR/Makefile" ] || { echo "no Buildroot at $BUILDROOT_DIR" >&2; exit 1; }

M=(make -C "$BUILDROOT_DIR" O="$OUT" BR2_EXTERNAL="$OPENHC_DIR/board $REPO/board"
   BR2_DL_DIR="$DL" BR2_JLEVEL="$JOBS")

"${M[@]}" defconfig BR2_DEFCONFIG="$EFFECTIVE"
"${M[@]}" "${@:-all}"

echo ">> image: $OUT/images/"
