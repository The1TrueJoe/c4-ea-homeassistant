#!/usr/bin/env bash
#
# Build a Home Assistant image by DELEGATING to openHC's build.sh.
#
# This used to assemble the effective defconfig itself: ea-common + <board> +
# our deltas. That broke, and broke silently, for two reasons:
#
#   1. It hardcoded openHC board name "ea3", which upstream has since split into
#      ea3-v1 and ea3-v2. The concatenation simply pointed at a file that no
#      longer exists.
#   2. It knew nothing about openHC's ohc.features mechanism, so the kernel was
#      built WITHOUT the feature fragments -- no emmc, meaning no persistent
#      root, on an image whose entire purpose is a persistent Home Assistant.
#
# Both are the same underlying mistake: a second copy of upstream's composition
# logic, drifting the moment upstream changes. So we do not have one any more.
# openHC's build.sh takes OHC_EXTRA_DEFCONFIG (appended last, so our
# assignments win) and OHC_EXTRA_EXTERNAL (so our packages and board files are
# visible to Buildroot), and does the rest.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
OPENHC_DIR="${OPENHC_DIR:-$REPO/openHC}"
BOARD="${BOARD:-ea3-ha}"

# Which upstream board each of ours layers onto.
#
# OPENHC_BOARD is overridable because the Home Assistant deltas are the SAME for
# every EA variant -- Python, the HA packages, /data, the init scripts. Only the
# hardware base differs. Duplicating a whole board directory per variant would
# duplicate the identical deltas with it, so the base is a parameter instead:
#
#     OPENHC_BOARD=ea3-v1 make image BOARD=ea3-ha
#
# which is how an EA-3 v1 (the one with Wi-Fi) is built.
case "$BOARD" in
    ea1-ha) OPENHC_BOARD="${OPENHC_BOARD:-ea1-v2}" ;;
    ea3-ha) OPENHC_BOARD="${OPENHC_BOARD:-ea3-v2}" ;;
    *) echo "BOARD must be ea1-ha or ea3-ha (got '$BOARD')" >&2; exit 1 ;;
esac

[ -f "$OPENHC_DIR/build/build.sh" ] || {
    echo "no openHC checkout at $OPENHC_DIR (submodule not initialized?)" >&2
    echo "  git submodule update --init openHC" >&2
    exit 1
}
[ -d "$OPENHC_DIR/board/$OPENHC_BOARD" ] || {
    echo "openHC has no board '$OPENHC_BOARD' -- did upstream rename it?" >&2
    echo "  available: $(cd "$OPENHC_DIR/board" && ls -d */ 2>/dev/null | tr -d / | tr '\n' ' ')" >&2
    exit 1
}

EXTRA="$REPO/board/$BOARD/${BOARD}_defconfig"
[ -f "$EXTRA" ] || { echo "missing $EXTRA" >&2; exit 1; }

echo ">> $BOARD = openHC/$OPENHC_BOARD + $(basename "$EXTRA")"

# GENERATE the rootfs-overlay line rather than hardcoding it.
#
# Buildroot has no "+=" for defconfig values and the concatenation is
# last-assignment-wins, so the final BR2_ROOTFS_OVERLAY has to repeat every
# upstream overlay and add ours. Hardcoding that meant naming an openHC board in
# our defconfig -- which pinned the file to ea3-v2 and silently dropped the
# board overlay for any other base -- and it also broke whenever upstream added
# an overlay. Both failure modes are quiet: you get an image that builds and is
# missing files.
#
# Only directories that exist are listed, so a base board with no overlay of its
# own (or a future one that gains a new layer) needs no edit here.
OVL=""
for d in common ea-common "$OPENHC_BOARD"; do
    [ -d "$OPENHC_DIR/board/$d/rootfs-overlay" ] && \
        OVL="$OVL \$(BR2_EXTERNAL_OPENHC_PATH)/$d/rootfs-overlay"
done
[ -d "$REPO/board/$BOARD/rootfs-overlay" ] && \
    OVL="$OVL \$(BR2_EXTERNAL_OHCHA_PATH)/$BOARD/rootfs-overlay"

GEN="$REPO/output/${BOARD}-extra.defconfig"
mkdir -p "$(dirname "$GEN")"
{
    cat "$EXTRA"
    echo ""
    echo "# --- generated by build/build.sh: overlays for base $OPENHC_BOARD ---"
    echo "BR2_ROOTFS_OVERLAY=\"${OVL# }\""
} > "$GEN"
EXTRA="$GEN"
echo ">> overlays:${OVL}"

# Our output and download dirs, not openHC's, so the two trees do not fight.
export BR2_OUTPUT_DIR="${BR2_OUTPUT_DIR:-$REPO/output/build/$BOARD}"
export BR2_DL_DIR="${BR2_DL_DIR:-$REPO/dl}"
export OHC_EXTRA_DEFCONFIG="$EXTRA"
export OHC_EXTRA_EXTERNAL="$REPO/board"
export BOARD="$OPENHC_BOARD"

exec bash "$OPENHC_DIR/build/build.sh" "$@"
